# ---------------------------------------------------------------- xmind 生成
_counter = [0]


def _id(prefix):
    _counter[0] += 1
    return "%s-%d" % (prefix, _counter[0])


def make_topic(title, children=None):
    topic = {"id": _id("t"), "title": title}
    if children:
        topic["children"] = {"attached": children}
    return topic


def build_sheet(root_title, groups, with_expect=True):
    branches = []
    for group_name, cases in groups:
        case_nodes = []
        for cid, title, *rest in cases:
            expect = rest[0] if rest else ""
            if with_expect and expect:
                case_nodes.append(make_topic(
                    "%s %s" % (cid, title),
                    [make_topic("预期：%s" % expect)],
                ))
            else:
                case_nodes.append(make_topic("%s %s" % (cid, title)))
        branches.append(make_topic(
            "%s（%d条）" % (group_name, len(cases)), case_nodes,
        ))
    total = sum(len(cases) for _, cases in groups)
    root = make_topic("%s（共%d条）" % (root_title, total), branches)
    return [{
        "id": _id("sheet"),
        "class": "sheet",
        "title": "Sheet 1",
        "rootTopic": root,
        "topicPositioning": "fixed",
    }]


def write_xmind(filename, sheets):
    content = json.dumps(sheets, ensure_ascii=False).encode("utf-8")
    metadata = json.dumps(
        {"creator": {"name": "Claude Code", "version": "1.0"}},
        ensure_ascii=False,
    ).encode("utf-8")
    manifest = json.dumps(
        {"file-entries": {"content.json": {}, "metadata.json": {}}},
        ensure_ascii=False,
    ).encode("utf-8")
    path = os.path.join(OUT_DIR, filename)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("content.json", content)
        zf.writestr("metadata.json", metadata)
        zf.writestr("manifest.json", manifest)
    print("generated: %s" % path)


